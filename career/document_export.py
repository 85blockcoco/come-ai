"""Local DOCX/PDF exports for the controlled Career markdown subset.

The input is plain, saved Markdown (headings, paragraphs and bullets), never
HTML.  It is treated as text throughout: no macros, hyperlinks, external
relationships, JavaScript or remote resources are generated.
"""

from __future__ import annotations

import html
import os
import re
import tempfile
import zipfile

from dataclasses import dataclass
from pathlib import Path
from typing import Iterator


@dataclass(frozen=True)
class MarkdownBlock:
    kind: str
    text: str


def _clean_text(value: str, *, limit: int = 40_000) -> str:
    return str(value or "").replace("\x00", "").replace("\r\n", "\n").replace("\r", "\n").strip()[:limit]


def iter_markdown_blocks(markdown: str) -> Iterator[MarkdownBlock]:
    """Parse only the small, inert subset generated by Application Studio."""
    paragraph: list[str] = []

    def flush() -> Iterator[MarkdownBlock]:
        nonlocal paragraph
        if paragraph:
            yield MarkdownBlock("paragraph", "\n".join(paragraph))
            paragraph = []

    for raw in _clean_text(markdown).splitlines():
        line = raw.strip()
        if not line:
            yield from flush()
            continue
        match = re.match(r"^(#{1,3})\s+(.+)$", line)
        if match:
            yield from flush()
            yield MarkdownBlock(f"heading{len(match.group(1))}", match.group(2).strip())
            continue
        if line.startswith("- "):
            yield from flush()
            yield MarkdownBlock("bullet", line[2:].strip())
            continue
        paragraph.append(line)
    yield from flush()


def _inline_parts(value: str) -> list[tuple[str, bool]]:
    """Return literal text and **bold** spans; all other markdown is text."""
    text = _clean_text(value, limit=10_000)
    parts: list[tuple[str, bool]] = []
    cursor = 0
    for match in re.finditer(r"\*\*(.+?)\*\*", text):
        if match.start() > cursor:
            parts.append((text[cursor : match.start()], False))
        parts.append((match.group(1), True))
        cursor = match.end()
    if cursor < len(text):
        parts.append((text[cursor:], False))
    return parts or [("", False)]


def _remove_word_paragraph_borders(element: object, qn: object) -> None:
    """Strip Word's built-in blue title rule from a style or paragraph.

    The stock ``Title`` style in some Word/LibreOffice templates carries a
    bottom paragraph border.  Career exports use the semantic Title style but
    deliberately keep the page visually neutral and printable.
    """
    finder = getattr(element, "find", None)
    if not callable(finder):
        return
    properties = finder(qn("w:pPr"))
    if properties is None:
        return
    for border in list(properties.findall(qn("w:pBdr"))):
        properties.remove(border)


def _atomic_target(target: Path) -> tuple[Path, int]:
    target.parent.mkdir(parents=True, exist_ok=True)
    descriptor, raw = tempfile.mkstemp(prefix=f".{target.stem}-", suffix=target.suffix, dir=target.parent)
    return Path(raw), descriptor


def _commit_temp(temporary: Path, descriptor: int, target: Path) -> None:
    try:
        os.close(descriptor)
    except OSError:
        pass
    try:
        os.chmod(temporary, 0o600)
    except OSError:
        pass
    os.replace(temporary, target)
    try:
        os.chmod(target, 0o600)
    except OSError:
        pass


def _discard_temp(temporary: Path, descriptor: int) -> None:
    try:
        os.close(descriptor)
    except OSError:
        pass
    temporary.unlink(missing_ok=True)


def _normalize_docx_archive(path: Path) -> None:
    """Make the DOCX byte-for-byte reproducible.

    python-docx copies the archive timestamp of every ZIP entry from the
    current clock. Two exports of identical content therefore differ even
    though no visible byte changed. Rewriting the archive with a fixed
    timestamp keeps the OPC structure intact and makes integrity hashes
    meaningful (SPEC-007, job ``deterministic-docx``).
    """
    with zipfile.ZipFile(path) as source:
        entries = [(info.filename, source.read(info.filename)) for info in source.infolist()]
    with zipfile.ZipFile(path, "w", compression=zipfile.ZIP_DEFLATED) as target:
        for name, payload in entries:
            info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o600 << 16
            target.writestr(info, payload)


def write_docx(*, markdown: str, title: str, language: str, target: Path) -> None:
    """Write a clean, editable DOCX with no external or executable content."""
    from docx import Document
    from docx.enum.style import WD_STYLE_TYPE
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.oxml.ns import qn
    from docx.shared import Inches, Mm, Pt, RGBColor

    temporary, descriptor = _atomic_target(target)
    try:
        document = Document()
        section = document.sections[0]
        # The Career workflow targets European applications, so exports use
        # A4 rather than the Word template's default US Letter format.
        section.page_width = Mm(210)
        section.page_height = Mm(297)
        section.top_margin = Inches(0.7)
        section.bottom_margin = Inches(0.7)
        section.left_margin = Inches(0.75)
        section.right_margin = Inches(0.75)

        normal = document.styles["Normal"]
        normal.font.name = "Arial"
        normal._element.rPr.rFonts.set(qn("w:ascii"), "Arial")
        normal._element.rPr.rFonts.set(qn("w:hAnsi"), "Arial")
        normal.font.size = Pt(10.5)
        normal.paragraph_format.space_after = Pt(7)
        normal.paragraph_format.line_spacing = 1.16

        for style_name, size in (("Title", 20), ("Heading 1", 13), ("Heading 2", 11.5)):
            style = document.styles[style_name]
            style.font.name = "Arial"
            style._element.rPr.rFonts.set(qn("w:ascii"), "Arial")
            style._element.rPr.rFonts.set(qn("w:hAnsi"), "Arial")
            style.font.size = Pt(size)
            style.font.color.rgb = RGBColor(0, 0, 0)
        document.styles["Title"].font.bold = True
        document.styles["Heading 1"].font.bold = True
        document.styles["Heading 2"].font.bold = True
        document.styles["Heading 1"].paragraph_format.space_before = Pt(13)
        document.styles["Heading 1"].paragraph_format.space_after = Pt(5)
        document.styles["Heading 2"].paragraph_format.space_before = Pt(10)
        document.styles["Heading 2"].paragraph_format.space_after = Pt(4)
        _remove_word_paragraph_borders(document.styles["Title"]._element, qn)
        if "Career Bullet" not in document.styles:
            bullet_style = document.styles.add_style("Career Bullet", WD_STYLE_TYPE.PARAGRAPH)
            bullet_style.base_style = document.styles["Normal"]
            bullet_style.paragraph_format.left_indent = Inches(0.24)
            bullet_style.paragraph_format.first_line_indent = Inches(-0.14)
            bullet_style.paragraph_format.space_after = Pt(3)

        first_title = True
        for block in iter_markdown_blocks(markdown):
            if block.kind == "heading1":
                paragraph = document.add_paragraph(style="Title" if first_title else "Heading 1")
                first_title = False
            elif block.kind == "heading2":
                paragraph = document.add_paragraph(style="Heading 1")
            elif block.kind == "heading3":
                paragraph = document.add_paragraph(style="Heading 2")
            elif block.kind == "bullet":
                paragraph = document.add_paragraph(style="Career Bullet")
                paragraph.add_run("• ")
            else:
                paragraph = document.add_paragraph(style="Normal")
            for index, line in enumerate(block.text.split("\n")):
                if index:
                    paragraph.add_run().add_break()
                for text, bold in _inline_parts(line):
                    run = paragraph.add_run(text)
                    run.bold = bold
            if block.kind == "heading1":
                paragraph.alignment = WD_ALIGN_PARAGRAPH.LEFT
                _remove_word_paragraph_borders(paragraph._p, qn)

        if not list(iter_markdown_blocks(markdown)):
            document.add_paragraph(_clean_text(title) or "Document de candidature")
        document.core_properties.title = _clean_text(title, limit=300)
        document.core_properties.subject = "Dossier de candidature"
        document.core_properties.author = ""
        document.core_properties.comments = ""
        document.core_properties.keywords = ""
        document.core_properties.language = _clean_text(language, limit=16)
        # python-docx writes to a path; closing the mkstemp descriptor first
        # is necessary on Windows and harmless on macOS.
        os.close(descriptor)
        descriptor = -1
        document.save(temporary)
        _normalize_docx_archive(temporary)
        _commit_temp(temporary, descriptor, target)
    except Exception:
        _discard_temp(temporary, descriptor)
        raise


def _reportlab_text(value: str) -> str:
    """Escape text for ReportLab and keep the requested Western languages intact."""
    # Standard PDF fonts use WinAnsi. French, English, Italian and German
    # accents are supported; exotic unsupported codepoints degrade safely to
    # a visible replacement instead of breaking document generation.
    safe = _clean_text(value, limit=10_000).replace("—", "-").replace("–", "-")
    safe = safe.encode("cp1252", errors="replace").decode("cp1252")
    escaped = html.escape(safe)
    return re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", escaped)


def write_pdf(*, markdown: str, title: str, language: str, target: Path) -> None:
    """Write a local, simple PDF without scripts, actions or external assets."""
    from reportlab.lib import colors
    from reportlab.lib.enums import TA_LEFT
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import inch
    from reportlab.platypus import ListFlowable, ListItem, Paragraph, SimpleDocTemplate

    temporary, descriptor = _atomic_target(target)
    try:
        os.close(descriptor)
        descriptor = -1
        stylesheet = getSampleStyleSheet()
        base = ParagraphStyle(
            "CareerBody",
            parent=stylesheet["BodyText"],
            fontName="Helvetica",
            fontSize=10.5,
            leading=15,
            textColor=colors.HexColor("#172321"),
            spaceAfter=8,
            alignment=TA_LEFT,
        )
        styles = {
            "heading1": ParagraphStyle(
                "CareerTitle",
                parent=base,
                fontName="Helvetica-Bold",
                fontSize=19,
                leading=23,
                textColor=colors.HexColor("#000000"),
                spaceAfter=12,
            ),
            "heading2": ParagraphStyle(
                "CareerHeadingOne",
                parent=base,
                fontName="Helvetica-Bold",
                fontSize=13,
                leading=17,
                textColor=colors.HexColor("#000000"),
                spaceBefore=10,
                spaceAfter=5,
            ),
            "heading3": ParagraphStyle(
                "CareerHeadingTwo",
                parent=base,
                fontName="Helvetica-Bold",
                fontSize=11.5,
                leading=15,
                textColor=colors.HexColor("#000000"),
                spaceBefore=7,
                spaceAfter=4,
            ),
        }
        story: list[object] = []
        bullets: list[ListItem] = []

        def flush_bullets() -> None:
            nonlocal bullets
            if bullets:
                story.append(
                    ListFlowable(
                        bullets,
                        bulletType="bullet",
                        leftIndent=18,
                        bulletFontName="Helvetica",
                        bulletFontSize=8,
                        spaceAfter=6,
                    )
                )
                bullets = []

        for block in iter_markdown_blocks(markdown):
            if block.kind == "bullet":
                bullets.append(ListItem(Paragraph(_reportlab_text(block.text), base), leftIndent=8))
                continue
            flush_bullets()
            style = styles.get(block.kind, base)
            content = "<br/>".join(_reportlab_text(line) for line in block.text.split("\n"))
            story.append(Paragraph(content, style))
        flush_bullets()
        if not story:
            story.append(Paragraph(_reportlab_text(title) or "Document de candidature", styles["heading1"]))
        document = SimpleDocTemplate(
            str(temporary),
            pagesize=A4,
            leftMargin=0.75 * inch,
            rightMargin=0.75 * inch,
            topMargin=0.7 * inch,
            bottomMargin=0.7 * inch,
            title=_reportlab_text(title),
            author="",
        )
        document.build(story)
        _commit_temp(temporary, descriptor, target)
    except Exception:
        _discard_temp(temporary, descriptor)
        raise
