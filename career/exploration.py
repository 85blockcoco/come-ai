"""Pure admission rules for the curated, read-only internship explorer.

Admission is deliberately separate from matching: a financial permanent
position is never made into an internship by a good relevance score. Evidence
quotes are taken verbatim from the posting, not generated by an AI model.
"""

from __future__ import annotations

import hashlib
import json
import re
from typing import Any, Protocol

from .models import canonical_url, clean_text


# The curated registry currently contains twenty-five reviewed sources. Twenty-
# eight keeps one explicit refresh able to cover all of them while preserving a
# hard resource bound and a small margin for later reviewed additions.
EXPLORATION_MAX_SOURCES = 28
EXPLORATION_MAX_RESULTS = 150
EXPLORATION_NETWORK_BUDGET_SECONDS = 60
EXPLORATION_LAST_SETTING = "stage_explorer_last_result"


class InternshipConnector(Protocol):
    """Connector extension point; future ATSs must enforce admission locally."""

    def discover_internships(
        self, source: Any, *, selection_brief: dict[str, Any], deadline: float | None = None
    ) -> Any:
        """Return bounded, classified and ranked postings plus factual counts."""


_TITLE_STAGE = re.compile(r"\b(?:intern(?:ship)?s?|stagiaires?|stages?)\b", re.I)
_PERMANENT = re.compile(r"\b(?:CDI|permanent(?:\s+(?:role|position|contract))?|contrat\s+ind[eé]termin[eé])\b", re.I)
_SENIOR_TITLE = re.compile(
    r"\b(?:senior|sr\.?|lead|head|director|directeur|directrice|manager|vice[ -]president|VP|principal|chief|responsable)\b",
    re.I,
)
_DESCRIPTION_STAGE = re.compile(
    r"\b(?:this\s+(?:is\s+an?\s+)?internship|"
    r"ce\s+stage|offre\s+de\s+stage|stage\s+(?:de\s+\d+|[àa]\s+pourvoir)|"
    r"nous\s+recherchons\s+(?:un|une)\s+stagiaire)\b",
    re.I,
)
_CURRENT_INTERN_ROLE = re.compile(
    r"(?:^|[.!?\n])\s*(?:as\s+an?\s+intern|we\s+are\s+(?:seeking|looking\s+for)\s+an?\s+intern)\b", re.I
)
_MIXED_GRADUATE = re.compile(
    r"\b(?:intern(?:ship)?\s*(?:or|/|and)\s*graduate|graduate\s*(?:or|/|and)\s*intern(?:ship)?)\b", re.I
)
_GRADUATE = re.compile(r"\bgraduate\b", re.I)
_PERMANENT_ROLE = re.compile(
    r"\b(?:this\s+(?:is\s+)?(?:an?\s+)?permanent\s+(?:role|position)|"
    r"(?:contract|contrat)\s*[:\-]\s*(?:permanent|CDI)|poste\s+en\s+CDI)\b", re.I
)
_NEGATIVE_STAGE = re.compile(r"\b(?:not\s+an?\s+internship|no\s+internships?|pas\s+un\s+stage)\b", re.I)


def _evidence(field: str, text: str, match: re.Match[str]) -> dict[str, str]:
    start = max(0, match.start() - 65)
    end = min(len(text), match.end() + 100)
    return {"field": field, "quote": text[start:end]}


def classify_internship(job: dict[str, Any]) -> dict[str, Any]:
    """Conservative classification; unknown/contradictory posts stay excluded.

    Full-time is not a permanent-contract marker: internships can be full-time.
    Previous internships in requirements/benefits are not positive evidence.
    """
    title = clean_text(job.get("title"), limit=300)
    employment = clean_text(job.get("employment_type"), limit=120)
    description = clean_text(job.get("description_original"), limit=30_000)
    evidence: list[dict[str, str]] = []
    for field, text in (("title", title), ("employment_type", employment)):
        mixed = _MIXED_GRADUATE.search(text)
        if mixed:
            return {"status": "uncertain", "reason": "L’annonce propose plusieurs types de contrat (graduate ou stage).",
                    "evidence": [_evidence(field, text, mixed)]}
    for field, text, pattern in (
        ("employment_type", employment, _PERMANENT),
        ("title", title, _PERMANENT),
        ("title", title, _SENIOR_TITLE),
    ):
        found = pattern.search(text)
        if found:
            return {"status": "excluded", "reason": "Contrat permanent ou niveau senior/encadrement explicite.",
                    "evidence": [_evidence(field, text, found)]}
    title_stage = _TITLE_STAGE.search(title)
    structured_stage = _TITLE_STAGE.search(employment)
    graduate_contract = _GRADUATE.search(employment)
    if graduate_contract:
        return {"status": "uncertain", "reason": "Le type de contrat publié est graduate, non un stage confirmé.",
                "evidence": [_evidence("employment_type", employment, graduate_contract)]}
    description_stage = _DESCRIPTION_STAGE.search(description) or _CURRENT_INTERN_ROLE.search(description)
    graduate_title = _GRADUATE.search(title)
    if graduate_title and not title_stage and not structured_stage:
        return {"status": "uncertain", "reason": "Le titre désigne un poste graduate, sans type stage explicite pour ce poste.",
                "evidence": [_evidence("title", title, graduate_title)]}
    mixed_description = _MIXED_GRADUATE.search(description)
    if mixed_description and not title_stage and not structured_stage:
        return {"status": "uncertain", "reason": "Le texte décrit indistinctement un graduate ou un stage.",
                "evidence": [_evidence("description_original", description, mixed_description)]}
    for field, text, found in (("title", title, title_stage), ("employment_type", employment, structured_stage),
                               ("description_original", description, description_stage)):
        if found:
            evidence.append(_evidence(field, text, found))
    contradictory = _PERMANENT_ROLE.search(description) or _NEGATIVE_STAGE.search(description)
    if contradictory:
        evidence.append(_evidence("description_original", description, contradictory))
        return {"status": "uncertain", "reason": "Le texte contredit ou rend ambigu le type de contrat.", "evidence": evidence[:4]}
    if evidence:
        return {"status": "confirmed", "reason": "Stage mentionné explicitement dans les faits de l’annonce.", "evidence": evidence[:3]}
    return {"status": "uncertain", "reason": "Le type de contrat n’est pas explicitement un stage.", "evidence": []}


_NON_FINANCE_TITLE = re.compile(
    r"\b(?:software|frontend|backend|full[ -]stack|site\s+reliability|human\s+resources|HR|"
    r"recruit(?:ing|ment|er)?|talent\s+acquisition|marketing|graphic\s+design|"
    r"reception(?:ist)?|product\s+design(?:er|ers|ing)?|data\s*cent(?:er|re)|talent\s+communit(?:y|ies)|"
    r"IT\s+operations?|engineering|engineer|security|cybersecurity|FPGA|hardware)\b", re.I
)
_FINANCIAL_TECHNICAL_TITLE = re.compile(
    r"\b(?:financial\s+engineer(?:ing)?|(?:quantitative|quant)\s+(?:research(?:er)?|trading|trader|analyst))\b", re.I
)


def criteria_admit(match: dict[str, Any], job: dict[str, Any] | None = None,
                   brief: dict[str, Any] | None = None) -> bool:
    """Apply contract/month eligibility, then domain and location criteria."""
    if job is not None and brief is not None:
        # Local import avoids coupling the pure offer parser to this module.
        from .offer_qualification import qualify_offer
        qualification = job.get("qualification")
        if not isinstance(qualification, dict):
            qualification = qualify_offer(
                job,
                allowed_contract_types=brief.get("contract_types"),
                allowed_start_months=brief.get("start_months"),
                required_start_date=brief.get("start_date"),
                minimum_stage_duration_months=brief.get("minimum_stage_duration_months", 6),
                excluded_countries=brief.get("excluded_countries"),
                excluded_cities=brief.get("excluded_cities"),
                require_known_location=brief.get("require_known_location", False),
            ).to_dict()
        if qualification.get("target_status") == "non_conforming":
            return False
    title = str(job.get("title") or "") if job else ""
    requested_technical_role = bool(brief and any(
        _NON_FINANCE_TITLE.search(str(role)) and str(role).casefold() in title.casefold()
        for role in brief.get("roles", [])
    ))
    if (job and brief and brief.get("domains") and _NON_FINANCE_TITLE.search(title)
        and not _FINANCIAL_TECHNICAL_TITLE.search(title) and not requested_technical_role):
        # Investment-firm boilerplate is not evidence that a software/HR role
        # does the financial work requested by the person.
        return False
    for component in match.get("components", []):
        if component.get("key") == "domaine" and component.get("status") != "match":
            return False
        if component.get("key") == "localisation" and component.get("status") == "no_match":
            # A missing country is not evidence that the source city is in a
            # different country. Keep unknowns visible rather than fabricate
            # a geographic inference from city strings.
            if job is None or brief is None:
                return False
            if (brief.get("cities") and job.get("city")) or (brief.get("countries") and job.get("country")):
                return False
    return True


def ranking_key(job: dict[str, Any], match: dict[str, Any]) -> tuple[Any, ...]:
    digest = hashlib.sha256(json.dumps(job, sort_keys=True, ensure_ascii=False).encode("utf-8")).hexdigest()
    status = (job.get("qualification") or {}).get("target_status")
    eligibility_order = {"conforming": 0, "to_verify": 1, "non_conforming": 2}.get(status, 0)
    return (eligibility_order, -(int(match["score"]) if match.get("score") is not None else 0),
            (match.get("education_access") or {}).get("priority_rank", 2),
            str(job.get("company") or "").casefold(), str(job.get("source_name") or ""),
            str(job.get("source_id") or ""), canonical_url(job.get("official_url")), digest)
