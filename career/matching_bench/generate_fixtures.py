"""Deterministic generator of the synthetic CV/offer couples (CVBOOST-08).

The bench is only as trustworthy as its fixtures, so the suite is generated by
code rather than hand-typed: the same generator always produces the same
JSON, and the committed JSON can be re-derived and compared at any time::

    PYTHONPATH=. python -m career.matching_bench.generate_fixtures --check

Everything here is synthetic: fake companies, fake postings, fake profiles and
reserved example domains (``exemple-fake.test``).  No real offer, no real
person, no real contact data.

Each case couples a synthetic profile with a synthetic offer and states, by
hand, the ground truth:

* which passages are real requirements and which are not (benefits, negated
  statements, prose);
* whether the profile really evidences a requirement — the *decisive* part
  counts, not a shared word;
* whether the offer is admissible for the declared criteria;
* what academic level the offer really advertises.

The bench compares that ground truth with the observed behaviour of the
application.  Nothing here changes a business rule: this module only writes
data.
"""

