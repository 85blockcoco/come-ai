def build_payload() -> dict[str, Any]:
    """The versioned JSON payload of the bench."""
    return {
        "schema_version": contracts.SCHEMA_VERSION,
        "suite_version": contracts.SUITE_VERSION,
        "generated_by": "career.matching_bench.generate_fixtures",
        "cases": CASES,
    }


def render(payload: dict[str, Any]) -> str:
    return json.dumps(payload, ensure_ascii=False, indent=2) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Genere les couples synthetiques du banc CVBOOST-08.")
    parser.add_argument("--check", action="store_true",
                        help="verifie que le JSON versionne correspond au generateur (sans l'ecrire)")
    parser.add_argument("--output", default=str(DATA_PATH), help="chemin du fichier JSON a ecrire")
    arguments = parser.parse_args(argv)
    payload = build_payload()
    rendered = render(payload)
    target = Path(arguments.output)
    if arguments.check:
        if not target.is_file():
            print(f"Fichier absent : {target}", file=sys.stderr)
            return 1
        if target.read_text(encoding="utf-8") != rendered:
            print(f"Le fichier versionne differe du generateur : {target}", file=sys.stderr)
            return 1
        print(f"OK : {target} correspond au generateur ({len(payload['cases'])} cas).")
        return 0
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(rendered, encoding="utf-8")
    print(f"{target} ecrit ({len(payload['cases'])} cas synthetiques).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
