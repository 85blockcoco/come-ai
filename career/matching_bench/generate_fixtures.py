def p(
    skills: str = "",
    experience: str = "",
    education: str = "",
    languages: str = "",
    eligibility: str = "",
    contact: dict[str, str] | None = None,
) -> dict[str, Any]:
    """A synthetic approved profile."""
    return {
        "fields": {
            "skills": skills,
            "experience": experience,
            "education": education,
            "languages": languages,
            "eligibility": eligibility,
        },
        "contact": dict(CONTACT) if contact is None else contact,
    }


def o(**overrides: Any) -> dict[str, Any]:
    """A synthetic offer; ``None`` removes a field instead of emptying it."""
    fields = dict(DEFAULT_OFFER)
    for key, value in overrides.items():
        if value is None:
            fields.pop(key, None)
        else:
            fields[key] = value
    return {"fields": fields}


def req(ref: str, should_be: bool, supported: bool, reason: str) -> dict[str, Any]:
    """One ground-truth statement about one passage of the offer."""
    return {
        "ref": ref,
        "should_be_requirement": should_be,
        "supported": supported,
        "reason": reason,
    }


def case(
    case_id: str,
    family: str,
    axis: str,
    title: str,
    severity: str,
    profile: dict[str, Any],
    offer: dict[str, Any],
    requirements: list[dict[str, Any]],
    eligibility: str,
    education_status: str,
    *,
    criteria: dict[str, Any] | None = None,
    brief: dict[str, Any] | None = None,
    unknown_dimensions: list[str] | None = None,
    relevance: dict[str, Any] | None = None,
    notes: str = "",
) -> dict[str, Any]:
    """One synthetic CV/offer couple with its hand-written ground truth."""
    return {
        "id": case_id,
        "family": family,
        "axis": axis,
        "title": title,
        "severity": severity,
        "profile": profile,
        "offer": offer,
        "criteria": dict(DEFAULT_CRITERIA) if criteria is None else criteria,
        "brief": dict(DEFAULT_BRIEF) if brief is None else brief,
        "oracle": {
            "eligibility": eligibility,
            "education_status": education_status,
            "requirements": requirements,
            "unknown_dimensions": list(unknown_dimensions or []),
            "relevance": dict(relevance or {}),
        },
        "notes": notes,
    }


